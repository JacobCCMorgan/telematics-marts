"""Write reports/marts_report.md and reports/summary.json from the exported marts.

Everything the README quotes comes from here, so a number in the README can always be traced to a table.
"""
from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
MARTS = ROOT / "data" / "marts"
REPORTS = ROOT / "reports"


def load(name: str) -> pd.DataFrame:
    return pd.read_parquet(MARTS / f"{name}.parquet")


def pct(x: float, digits: int = 1) -> str:
    return f"{100 * x:.{digits}f} %"


def main() -> None:
    REPORTS.mkdir(exist_ok=True)
    manifest = json.loads((MARTS / "manifest.json").read_text())
    fleet = load("rpt_fleet_snapshot").set_index("metric")
    gen = load("rpt_online_rate_by_generation")
    tiers = load("rpt_device_priority_tiers")
    changes = load("rpt_subscription_slot_changes").sort_values("slots", ascending=False).set_index("outcome")
    purged = load("rpt_organizations_purged_after_2024").iloc[0]
    window = load("fct_device_anomaly_window")
    terms = load("fct_contract_term")
    snap = load("snap_subscription_slot")
    orgs = load("dim_organization")

    cust = window[~window["is_internal_test"]]
    classes = cust.groupby("severity_class").agg(devices=("device_key", "size"), silent_3day=("moving_silent_reports_3day", "sum"),
                                                 observed=("observed_day4", "sum"), severe=("is_severe_day4", "sum")).reindex(["chronic", "intermittent", "transient"])
    flags = {c: int(terms[c].sum()) for c in terms.columns if c.startswith("flag_")}
    versions = snap.groupby(["dbt_valid_from", "dbt_is_deleted"]).size()

    summary = {
        "tables": {k: v["rows"] for k, v in manifest.items()},
        "fleet_snapshot": {m: {"value": int(r["value"]), "denominator": (None if pd.isna(r["denominator"]) else int(r["denominator"])),
                               "share": (None if pd.isna(r["share"]) else round(float(r["share"]), 6))} for m, r in fleet.iterrows()},
        "online_rate_by_generation": {r["hw_generation"]: {"reporting_units": int(r["reporting_units"]), "online_rate": round(float(r["online_rate"]), 6)} for _, r in gen.iterrows()},
        "anomaly_window": {
            "flagged_customer_devices": len(cust),
            "flagged_internal_test_devices": int(window["is_internal_test"].sum()),
            "silent_reports_3day_customer": int(cust["moving_silent_reports_3day"].sum()),
            "observed_day4": int(cust["observed_day4"].sum()),
            "severe_day4": int(cust["is_severe_day4"].sum()),
            "classes": {c: {"devices": int(r["devices"]), "silent_3day": int(r["silent_3day"]), "observed_day4": int(r["observed"]), "severe_day4": int(r["severe"])} for c, r in classes.iterrows()},
            "tiers": {r["priority_tier"]: {"devices": int(r["devices"]), "severe_day4_share": round(float(r["severe_day4_share"]), 6),
                                          "share_of_day4_silent_reports": round(float(r["share_of_day4_silent_reports"]), 6)} for _, r in tiers.iterrows()},
        },
        "contract_terms": {"customer_rows": len(terms), "flags": flags,
                           "organizations_by_lifecycle_status": {k: int(v) for k, v in orgs[~orgs["is_internal_test"]]["lifecycle_status"].value_counts().items()}},
        "subscription_slot_snapshot": {
            "versions": {f"{d.date()}|deleted={x}": int(n) for (d, x), n in versions.items()},
            "slots_active_2024": int(changes["slots"].sum()),
            "outcomes_2024_to_2026": {o: {"slots": int(r["slots"]), "share": round(float(r["share_of_slots"]), 6), "organizations": int(r["organizations"])} for o, r in changes.iterrows()},
            "organizations_active_2024": int(purged["organizations_active_2024"]),
            "organizations_purged": int(purged["organizations_purged"]),
        },
    }
    (REPORTS / "summary.json").write_text(json.dumps(summary, indent=2) + "\n")

    lines = [
        "# telematics-marts: what the modeling layer shows",
        "",
        "Generated by `scripts/write_report.py` from the exported tables in `data/marts/`. Snapshot date of the",
        "foundation tables: 2026-09-28; earlier CRM export: 2024-01-05. Customer units and organisations only;",
        "the provider's bench devices and test organisations are excluded from every figure.",
        "",
        "## Tables",
        "",
        "| table | rows | grain |",
        "|---|---:|---|",
    ]
    grains = {
        "dim_device": "ELD unit", "dim_vehicle": "VIN (current registration)", "dim_driver_account": "driver login account",
        "dim_organization": "organisation", "fct_contract_term": "vehicle subscription slot, 2026-09-28 export (customer rows)",
        "fct_device_day": "device x day of moving-while-silent telemetry", "fct_device_anomaly_window": "device flagged 23-25 Sep 2026",
        "rpt_fleet_snapshot": "metric", "rpt_online_rate_by_generation": "hardware generation", "rpt_device_priority_tiers": "priority tier",
        "rpt_subscription_slot_changes": "outcome of a 2024 slot", "rpt_organizations_purged_after_2024": "one row",
        "snap_subscription_slot": "slot version (type 2)",
    }
    for name, meta in manifest.items():
        lines.append(f"| `{name}` | {meta['rows']:,} | {grains.get(name, '')} |")
    lines += [
        "",
        "## Fleet snapshot (rpt_fleet_snapshot)",
        "",
        f"- {fleet.loc['registered_units']['value']:,} customer ELD units are registered; {fleet.loc['never_reported_units']['value']:,} ({pct(fleet.loc['never_reported_units']['share'])}) have never reported.",
        f"- Of the {fleet.loc['reporting_units']['value']:,} reporting units, {pct(fleet.loc['online_units']['share'])} were online at the snapshot"
        + "; by hardware generation: " + ", ".join(f"{r['hw_generation']} {pct(r['online_rate'], 0)}" for _, r in gen.iterrows()) + ".",
        (f"- {fleet.loc['last_reported_low_battery_units']['value']:,} reporting units ({pct(fleet.loc['last_reported_low_battery_units']['share'])}) last reported in low-battery mode, "
         f"{fleet.loc['backup_battery_at_most_20pct_units']['value']} are at 20 % backup battery or less, and {fleet.loc['not_updated_over_30_days_units']['value']:,} have not updated for more than 30 days."),
        f"- {pct(fleet.loc['never_read_vin_units']['share'], 0)} of reporting units have never read a VIN from the engine computer; {pct(fleet.loc['no_valid_gps_units']['share'])} have no valid GPS fix.",
        f"- {pct(fleet.loc['contract_terms_exactly_365_days']['share'], 0)} of contract terms are exactly 365 days; {fleet.loc['organizations_active']['value']:,} organisations are active and {fleet.loc['organizations_lapsed']['value']:,} lapsed.",
        "",
        "## ECM-disconnect window (fct_device_anomaly_window, rpt_device_priority_tiers)",
        "",
        (f"- {len(cust)} customer devices were flagged on 23-25 Sep 2026 with {int(cust['moving_silent_reports_3day'].sum()):,} moving-while-silent reports; "
         f"{int(window['is_internal_test'].sum())} bench devices are excluded."),
        "- Severity classes: " + "; ".join(f"{c} {int(r['devices'])} devices, {int(r['severe'])} of {int(r['observed'])} observed severe again on 28 Sep" for c, r in classes.iterrows()) + ".",
        "",
        "| tier | rule | devices | observed day 4 | severe day 4 | share of day-4 silent reports |",
        "|---|---|---:|---:|---:|---:|",
    ]
    for _, r in tiers.iterrows():
        lines.append(f"| {r['priority_tier']} | {r['rule']} | {int(r['devices'])} | {int(r['observed_day4'])} | {int(r['severe_day4'])} ({pct(r['severe_day4_share'], 0)}) | {pct(r['share_of_day4_silent_reports'], 0)} |")
    lines += [
        "",
        "## Contract terms (fct_contract_term)",
        "",
        f"- {len(terms):,} customer subscription rows. Rows flagged rather than corrected: "
        + ", ".join(f"{k.replace('flag_', '').replace('_', ' ')} {v}" for k, v in flags.items()) + ".",
        "- Organisations by lifecycle status: " + ", ".join(f"{k} {v:,}" for k, v in summary["contract_terms"]["organizations_by_lifecycle_status"].items()) + ".",
        "",
        "## Subscription-slot snapshot (snap_subscription_slot, rpt_subscription_slot_changes)",
        "",
        "- Versions: " + ", ".join(f"{k} {v:,}" for k, v in summary["subscription_slot_snapshot"]["versions"].items()) + ".",
        f"- Of the {int(changes['slots'].sum()):,} customer slots active in the January 2024 export:",
    ]
    for o, r in changes.iterrows():
        lines.append(f"  - {o.replace('_', ' ')}: {int(r['slots']):,} slots ({pct(r['share_of_slots'])}), {int(r['organizations']):,} organisations")
    lines += [
        f"- {int(purged['organizations_purged'])} of the {int(purged['organizations_active_2024']):,} organisations active in January 2024 ({pct(purged['purged_share'])}) have no dated contract row left in the 2026 export.",
        "",
    ]
    (REPORTS / "marts_report.md").write_text("\n".join(lines))
    print((REPORTS / "marts_report.md").read_text())


if __name__ == "__main__":
    main()
