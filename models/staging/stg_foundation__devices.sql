-- One row per ELD unit as registered in the device-management system (snapshot 2026-09-28).
-- Column names follow the foundation's data dictionary; only the hardware generation is normalised here.
select
    device_key,
    org_group                                   as batch_label,
    is_internal_test,
    model_code,
    coalesce(hw_version, right(model_code, 1))  as hw_generation,   -- A, B, C
    fw_version,
    st_fw_version,
    ble_fw_version,
    vin_key,
    is_placeholder_vin,
    driver_key,
    has_trailer_gps,
    vehicle_make,
    vehicle_year,
    engine_hours,
    engine_miles,
    engine_km,
    device_temp_c,
    rpm,
    speed_kmh,
    gps_speed_kmh,
    lat_coarse,
    lon_coarse,
    timezone_offset,
    report_ts,
    backup_battery_pct,
    car_battery_connected,
    mode                                        as last_mode,
    disk_used_pct,
    mileage_source_sa,
    gps_valid,
    connect_status,
    connect_ts,
    remaining_data_mb,
    last_updated_ts,
    created_ts,
    updated_ts,
    last_event_type,
    never_reported
from {{ source('foundation', 'dim_device') }}
